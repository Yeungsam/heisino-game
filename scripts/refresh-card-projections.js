// Mechanical migration: retain original OCR evidence, remove obsolete gameplay fields.
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'data/cards.json'), 'utf8'))
for (const card of catalog.cards) {
  delete card.durability
  if (card.category === 'WEAPON') card.description = `武器卡，攻击倍率${Math.round(card.attack_multiplier * 100)}%。`
  if (card.category === 'ARMOR') card.description = '防具卡，防御倍率等待玩法数值确认。'
}
for (const name of ['data/cards.json', 'functions/heisino-cards/cards.json']) {
  fs.writeFileSync(path.join(root, name), JSON.stringify(catalog, null, 2) + '\n')
}
const projection = catalog.cards.map(card => ({
  cardId: card.card_id, name: card.name, description: card.description, kind: card.kind,
  category: card.category, rarity: card.rarity, attackMultiplier: card.attack_multiplier,
  defenseMultiplier: card.defense_multiplier, value: card.economy.fixed_value ?? card.economy.purchase_price,
  assetPath: card.assets.card_art_path, dataStatus: card.data_status
}))
fs.writeFileSync(path.join(root, 'client/data/cards.js'), '// Generated by scripts/build-card-catalog.js from data/cards.json.\nmodule.exports = ' + JSON.stringify(projection, null, 2) + '\n')
const schemaPath = path.join(root, 'data/cards.schema.json')
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'))
schema.$defs.card.required = schema.$defs.card.required.filter(key => key !== 'durability')
delete schema.$defs.card.properties.durability
fs.writeFileSync(schemaPath, JSON.stringify(schema, null, 2) + '\n')
