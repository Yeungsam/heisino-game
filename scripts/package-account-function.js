const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
execFileSync(process.execPath, [path.join(__dirname, 'build-account-runtime.js')], { stdio: 'inherit' })
const output = path.join(root, 'output/deploy')
fs.mkdirSync(output, { recursive: true })
const archive = path.join(output, 'heisino-account-20261103.zip')
execFileSync('zip', ['-q', '-r', archive, 'index.js', 'service.js', 'store.js', 'wechat.js', 'http-handler.js', 'runtime.js', 'starter.json', 'package.json', 'package-lock.json', 'scf_bootstrap', 'runtime'], { cwd: path.join(root, 'functions/heisino-account') })
console.log(archive)
