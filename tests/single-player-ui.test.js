const test = require('node:test')
const assert = require('node:assert/strict')
const { simulation, dock, heartbeat, move, center } = require('./helpers/account-ui-simulation')

async function solo(app) {
  await dock(app)
  await app.tap('lobby_single')
  assert.equal(app.run('accountGame?.mode'), 'SINGLE')
}

test('单人第1轮：码头入口、开局回包丢失与一次扣仓', async t => {
  const sim = await simulation(t, 2)
  let outage = true
  const player = await sim.mount(0, { blockResponse: req => {
    if (outage && ['/api/account/start', '/api/account/resume'].includes(req.route)) throw new Error('request timeout')
  } })
  const other = sim.client[1]
  await dock(player)
  assert.ok(player.draw().includes('单人模式'))
  assert.equal(player.run('accountProfile.quantities.wp_006'), 1)
  await player.tap('lobby_single')
  assert.equal(player.run('scene'), 'LOBBY')
  const starts = player.requests.filter(req => req.route === '/api/account/start')
  assert.equal(starts.length, 2)
  assert.equal(starts[0].input.requestId, starts[1].input.requestId)
  const account = await sim.store.get(player.account.id)
  assert.equal(account.activeGame.mode, 'SINGLE')
  assert.equal(account.quantities.wp_006, 0)
  assert.equal(account.ledger.filter(entry => entry.type === 'DEPLOY').length, 1)
  await assert.rejects(other.api.command('game', { gameId: account.activeGame.gameId, turn: 1, action: 'move', target: { x: 1, y: 0 } }), { code: 'NO_ACTIVE_GAME' })

  outage = false
  await player.run('refreshLobby()')
  await player.idle()
  assert.equal(player.run('scene'), 'GAME', '开局已提交但回包丢失后，恢复网络应自动进入原对局')
  assert.equal(player.run('accountGame.gameId'), account.activeGame.gameId)
  assert.equal(player.read('accountGame.state.players').length, 1)
  assert.equal(player.hits('confirm_move').length, 1)
  assert.equal((await sim.store.get(player.account.id)).ledger.filter(entry => entry.type === 'DEPLOY').length, 1)
})

function nextRoll(sim, app, output) {
  const game = sim.store.documents.get(app.account.id).activeGame
  game.rngState = Number(BigInt.asUintN(32, (BigInt(output) - 1013904223n) * 4276115653n))
}

test('单人第2轮：守卫30%边界、逐房一次、金库与战斗结果截止', async t => {
  const sim = await simulation(t, 1)
  const [player] = sim.client
  await solo(player)
  nextRoll(sim, player, 0x4ccccccc)
  await player.tap('confirm_move')
  assert.equal(player.run('presentation'), 'ROOM')
  assert.equal(player.read('accountGame.state.players').length, 1)
  assert.deepEqual((await sim.store.get(player.account.id)).activeGame.botCheckedRooms, [])
  await player.tap('room_leave')

  nextRoll(sim, player, 0x4ccccccd)
  await move(player, 1, 0)
  assert.equal(player.run('presentation'), 'ROOM', '30% 以上不触发守卫')
  await player.tap('room_leave')
  nextRoll(sim, player, 0x4ccccccc)
  await player.tap('confirm_move')
  assert.equal(player.run('presentation'), 'ROOM', '第一次未触发的房间也不会重抽')
  assert.deepEqual((await sim.store.get(player.account.id)).activeGame.botCheckedRooms, ['n_1_0'])
  await player.tap('room_leave')

  nextRoll(sim, player, 0x4ccccccc)
  await move(player, 1, 1)
  assert.equal(player.run('presentation'), 'BATTLE')
  assert.match(player.draw().join('\n'), /赌场守卫[\s\S]*战斗胜利/)
  const bot = player.read('accountGame.state.players').find(unit => unit.isBot)
  assert.equal(bot.diceMode, 'ATTACK')
  assert.equal(bot.status, 'DEFEATED')
  assert.equal(player.run('engine.getPlayer("P1").hp'), 30)
  assert.deepEqual(player.read('accountGame.state.items').filter(item => item.state === 'DROPPED').map(item => item.cardId).sort(), ['ar_013', 'wp_004'])
  sim.tick(25000)
  await heartbeat(player)
  const oldContinue = player.hits('battle_continue')[0]
  player.touch('start', ...center(oldContinue.rect))
  sim.tick(25000)
  player.touch('end', ...center(oldContinue.rect))
  assert.equal(player.run('presentation'), 'BATTLE', '过期战斗按钮不能切入过期房间')
  assert.equal(player.hits('battle_continue').length, 0)
  assert.match(player.draw().join('\n'), /同步回合/)
  await heartbeat(player)
  assert.equal(player.run('engine.turn'), 5)
  assert.equal(player.run('presentation'), 'MAP')
  await move(player, 2, 1)
  if (player.hits('battle_continue').length) await player.tap('battle_continue')
  await player.tap('room_leave')
  assert.equal(player.run('engine.turn'), 6)
  nextRoll(sim, player, 0x4ccccccc)
  await move(player, 2, 2)
  assert.equal(player.run('presentation'), 'BATTLE')
  assert.ok((await sim.store.get(player.account.id)).activeGame.botCheckedRooms.includes('n_2_2'))
})

function drag(app, from, to) {
  const [x, y] = center(from)
  const [targetX, targetY] = center(to)
  app.touch('start', x, y)
  app.touch('move', targetX, y)
  app.touch('end', targetX, targetY)
}

test('单人第3轮：逐件曝光、拾取丢弃与搜索截止热区', async t => {
  const sim = await simulation(t, 1)
  const [player] = sim.client
  await solo(player)
  nextRoll(sim, player, 0x4ccccccd)
  await move(player, 1, 0)
  const area = player.read('searchVisitState.room.areas').find(item => item.itemCount > 0)
  await player.tap('room_area', hit => hit.data === area.areaId)
  assert.equal(player.run('presentation'), 'SEARCH')
  const game = (await sim.store.get(player.account.id)).activeGame
  const [hiddenId] = game.visit.observation.hiddenIds
  await assert.rejects(player.api.command('game', { gameId: game.gameId, turn: 1, action: 'pickup', instanceId: hiddenId }), { code: 'ITEM_NOT_VISIBLE' })
  sim.tick(1999)
  await heartbeat(player)
  player.draw()
  assert.equal(player.read('ui.searchItemRects').length, 0)
  sim.tick(1)
  await heartbeat(player)
  assert.match(player.draw().join('\n'), /搜索物品\s+1\//)
  const [loot] = player.read('ui.searchItemRects')
  assert.equal(loot.instanceId, hiddenId)
  drag(player, loot, player.read('ui.searchBackpackRect'))
  await player.idle()
  player.draw()
  const carried = player.read('ui.searchInventoryRects').find(item => item.instanceId === hiddenId)
  assert.ok(carried)
  drag(player, carried, player.read('ui.searchRoomRect'))
  await player.idle()
  assert.match(player.draw().join('\n'), /已丢弃 1 张卡牌/)
  const drops = player.read('searchVisitState.room.activeArea.visibleItems')
  assert.equal(drops.find(item => item.instanceId === hiddenId).state, 'DROPPED')

  sim.tick(24000)
  await heartbeat(player)
  const oldFinish = player.hits('search_finish')[0].rect
  const dropped = player.read('ui.searchItemRects').find(item => item.instanceId === hiddenId)
  const [x, y] = center(dropped)
  const [bagX, bagY] = center(player.read('ui.searchBackpackRect'))
  player.touch('start', x, y)
  player.touch('move', bagX, y)
  sim.tick(24000)
  const actionCount = player.requests.filter(req => req.route === '/api/account/game').length
  player.touch('end', bagX, bagY)
  await player.idle()
  assert.equal(player.requests.filter(req => req.route === '/api/account/game').length, actionCount,
    '零秒后的旧搜索拖拽不能发送过期拾取')
  player.touch('start', ...center(oldFinish))
  player.touch('end', ...center(oldFinish))
  await player.idle()
  assert.equal(player.requests.filter(req => req.route === '/api/account/game').length, actionCount)
  assert.equal(player.hits('search_finish').length, 0)
  assert.match(player.draw().join('\n'), /同步回合/)
  await heartbeat(player)
  assert.equal(player.run('engine.turn'), 2)
  assert.equal(player.run('presentation'), 'MAP')
  assert.equal((await sim.store.get(player.account.id)).activeGame.state.items.find(item => item.instanceId === hiddenId).state, 'DROPPED')
})

test('单人第4轮：搜索暂停、冷重启恢复与十分钟失败边界', async t => {
  const sim = await simulation(t, 1)
  const [player] = sim.client
  await solo(player)
  const gameId = player.run('accountGame.gameId')
  nextRoll(sim, player, 0x4ccccccc)
  await move(player, 1, 0)
  await player.tap('battle_continue')
  const game = (await sim.store.get(player.account.id)).activeGame
  const hidden = game.state.items.find(item => item.nodeId === game.visit.roomNodeId && item.state === 'HIDDEN')
  await player.tap('room_area', hit => hit.data === hidden.areaId)
  sim.tick(2000)
  await heartbeat(player)
  const visible = player.read('searchVisitState.room.activeArea.visibleItems').map(item => item.instanceId)
  assert.ok(visible.length > 0)
  const remaining = player.run('searchVisitState.visit.deadlineAt - Date.now()')
  player.events.hide()
  await player.idle()
  sim.tick(120000)
  const resumed = await sim.mount(0)
  assert.equal(resumed.run('accountGame.gameId'), gameId)
  assert.equal(resumed.run('presentation'), 'SEARCH')
  assert.equal(resumed.run('searchVisitState.room.activeAreaId'), hidden.areaId)
  assert.deepEqual(resumed.read('searchVisitState.room.activeArea.visibleItems').map(item => item.instanceId), visible)
  assert.equal(resumed.run('searchVisitState.visit.deadlineAt - Date.now()'), remaining)

  await resumed.tap('search_finish')
  assert.equal(resumed.run('presentation'), 'ROOM')
  resumed.events.hide()
  await resumed.idle()
  sim.tick(599999)
  const nearDeadline = await sim.mount(0)
  assert.equal(nearDeadline.run('accountGame.gameId'), gameId)
  assert.equal(nearDeadline.run('presentation'), 'ROOM', '已经完成搜索的房间重进不应重播战斗结果')
  assert.ok(nearDeadline.draw().includes('会客厅'))
  assert.equal(nearDeadline.hits('battle_continue').length, 0)

  nearDeadline.events.hide()
  await nearDeadline.idle()
  sim.tick(600000)
  const expired = await sim.mount(0)
  assert.equal(expired.run('presentation'), 'SETTLEMENT')
  assert.equal(expired.run('accountSettlement.status'), 'DISCONNECTED')
  assert.match(expired.draw().join('\n'), /中断超过 10 分钟/)
  assert.deepEqual(expired.read('accountProfile.quantities'), { wp_006: 0, ar_001: 1, sk_001: 1 })
  assert.equal([...sim.store.ledger.values()].filter(entry => entry.gameId === gameId && entry.type === 'SETTLEMENT').length, 1)
})

test('单人第5轮：守卫圆盾返仓、再次带入与换轮时确认放弃', async t => {
  const sim = await simulation(t, 1)
  let dialog
  const player = await sim.mount(0, { showModal: args => { dialog = args } })
  await solo(player)
  const gameId = player.run('accountGame.gameId')
  const route = [[1, 0], [2, 0], [3, 0], [4, 0], [4, 1], [4, 2], [4, 3], [4, 4]]
  for (const [step, [x, y]] of route.entries()) {
    nextRoll(sim, player, step === 0 || step === route.length - 1 ? 0x4ccccccc : 0x4ccccccd)
    await move(player, x, y)
    if (step === 0) {
      await player.tap('battle_continue')
      await player.tap('room_area', hit => hit.data === 'MAIN_TABLE')
      assert.ok(player.draw().includes('蓝'))
      const shield = player.read('ui.searchItemRects').find(rect => rect.cardId === 'ar_013')
      assert.ok(shield)
      drag(player, shield, player.read('ui.searchBackpackRect'))
      await player.idle()
      await player.tap('search_finish')
    }
    if (step < route.length - 1) await player.tap('room_leave')
  }
  assert.ok(player.draw().includes('撤离点'))
  assert.ok(!(await sim.store.get(player.account.id)).activeGame.botCheckedRooms.includes('n_4_4'))
  await player.tap('request_extraction')
  assert.equal(player.run('accountSettlement.status'), 'EXTRACTED')
  assert.match(player.draw().join('\n'), /撤\s*离\s*成\s*功/)
  assert.equal(player.run('accountProfile.quantities.ar_013'), 1)
  assert.equal(player.run('accountProfile.gold'), 0)
  await player.api.command('game', player.requests.find(req => req.input?.action === 'extract').input)
  assert.equal([...sim.store.ledger.values()].filter(entry => entry.gameId === gameId && entry.type === 'SETTLEMENT').length, 1)

  await player.tap('settlement_replay')
  assert.ok(player.draw().includes('蓝'))
  for (let tap = 0; tap < 2; tap++) await player.tap('loadout_warehouse_card', hit => hit.data === 'ar_013')
  await player.tap('loadout_match')
  await player.tap('lobby_single')
  const secondGame = player.run('accountGame.gameId')
  assert.notEqual(secondGame, gameId)
  assert.equal(player.run('accountProfile.quantities.ar_013'), 0)
  await player.tap('confirm_move')
  await player.tap('account_abandon')
  assert.match(dialog.title, /放弃本局/)
  dialog.success({ confirm: false })
  assert.equal(player.run('accountGame.gameId'), secondGame)
  sim.tick(25000)
  await heartbeat(player)
  await player.tap('account_abandon')
  sim.tick(25000)
  dialog.success({ confirm: true })
  await player.idle()
  assert.equal(player.run('presentation'), 'SETTLEMENT', '放弃的是整局，弹窗确认不应被换轮拒绝')
  assert.equal(player.run('accountSettlement.status'), 'ABANDONED')
  assert.equal(player.run('accountProfile.quantities.ar_013'), 0)
  assert.equal(player.run('accountProfile.quantities.wp_006'), 1)
  assert.match(player.draw().join('\n'), /已放弃对局/)
  const persisted = await sim.store.get(player.account.id)
  assert.equal(persisted.ledger.filter(entry => entry.gameId === secondGame && entry.type === 'SETTLEMENT').length, 1)
})
